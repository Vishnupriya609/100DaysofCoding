// in programmatic to find size
public class dataTypesSize {

	public static void main(String[] args) {
		
		// using wrapper classes  
		System.out.println("Short Size(bits) : " + Short.SIZE); // output : Short Size(bits) : 16
		System.out.println("Float Size(bytes) : " + Float.SIZE/8); // Output : Float Size(bytes) : 4
		System.out.println("Integer Size(bits) : " + Integer.SIZE/8);  // output ; Integer Size(bits) : 4
		

	}

}
