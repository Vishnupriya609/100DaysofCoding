package com.operators;

public class ternaryOperator {
	public static void main (String[] args) {
		   int i = 0;
		   int j = 30;
		   
           // finding max number in one line
		   System.out.println((i > j)? i : j); // 30
		   // find the number type 
		   System.out.println((i == 0) ? "Zero" :((i > 0) ? "Positive" : "Negative"));//Zero
		   
		   
	}
	  
}
