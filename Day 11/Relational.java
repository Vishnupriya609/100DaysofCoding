package com.operators;

public class Relational {

	public static void main(String[] args) {
		// compare the values & prints the boolean values
		int x = 10;
		int y = 20;
		System.out.println(x<y); // true
		System.out.println(x>y); // false
		System.out.println(x==y); // false
		System.out.println(x<=y); // true
		System.out.println(x>=y); // false
		System.out.println(x!=y); // true

	}

}
