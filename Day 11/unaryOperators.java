package com.operators;

public class unaryOperators {

	public static void main(String[] args) {
		// urnary operators only one operand
		int a = 12;
		
		System.out.println(+a); //12
		System.out.println(-a); //-12
		System.out.println(++a); //13
		System.out.println(a++); //13
		System.out.println(a); //14
		

	}

}
